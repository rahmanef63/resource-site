#!/usr/bin/env node
// audit-file-size.mjs — modularity guard.
//
// Enforces the "Max 200 lines per file" rule from lib/content/best-practices.ts.
// Scans .ts/.tsx/.mjs under shipped + audited directories. Files over the cap
// emit an error unless they're in EXEMPT_PATTERNS (pure data) or
// GRANDFATHERED (pre-existing tech debt — backlog-tracked, MUST shrink, not
// grow, over time).
//
// Run: node scripts/validation/audit-file-size.mjs [--check] [--list-grandfather]

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, "../..");

const CAP = 200;

// Roots to scan. Skip node_modules / .next / _generated by directory name.
const SCAN_ROOTS = [
  "frontend/slices",
  "frontend/shared",
  "components/templates",
  "components/site",
  "components/admin",
  "cookbook/layouts",
  "app",                       // full app tree (incl docs, admin, preview)
  "convex/features",
  "convex/_shared",
  "convex-templates",
  "lib",
  "hooks",
  "shared",
  "packages/cli/lib",
  "packages/cli/bin",
  "packages/cli/scripts",
  "packages/mcp/bin",
  "packages/mcp/src",
  "packages/shared/src",
  "scripts/features",
  "scripts/validation",
];

// Pure-data exports — splitting these into N files just spreads the same
// literal across more imports without modularity benefit. Permanently exempt.
const EXEMPT_PATTERNS = [
  /^lib\/content\/.+\.ts$/,            // catalog arrays: layouts, slices, recipes, etc.
  /^lib\/theme\/.+\.ts$/,              // theme preset literals
  /^lib\/preview-presets\.ts$/,        // preview-mode literals
  /^lib\/templates\/configs\.ts$/,     // template config registry
  /\/shared\/seed\.ts$/,               // per-template seed data
  /\/data\/.+\.ts$/,                   // /data/ subfolder = data literals
  /\/_generated\//,                    // Convex codegen
];

// Pre-existing files over the cap. Goal: this list SHRINKS, never GROWS.
// When you refactor a file off this list, delete its entry.
// To regenerate after a green refactor: `node scripts/validation/audit-file-size.mjs --list-grandfather > scripts/validation/audit-file-size.grandfather.json`
const GRANDFATHER_FILE = path.join(__dirname, "audit-file-size.grandfather.json");
const GRANDFATHERED = (() => {
  if (!existsSync(GRANDFATHER_FILE)) return new Set();
  const body = readFileSync(GRANDFATHER_FILE, "utf8").trim();
  if (!body) return new Set();
  try { return new Set(JSON.parse(body)); } catch { return new Set(); }
})();

const errors = [];
const warnings = [];
const offendersForList = [];

let scanned = 0;
for (const root of SCAN_ROOTS) {
  const abs = path.join(REPO, root);
  if (!existsSync(abs)) continue;
  for (const file of findSourceFiles(abs)) {
    scanned++;
    const rel = path.relative(REPO, file).replaceAll(path.sep, "/");
    if (EXEMPT_PATTERNS.some((re) => re.test(rel))) continue;

    const lines = readFileSync(file, "utf8").split("\n").length;
    if (lines <= CAP) continue;

    offendersForList.push(rel);
    if (GRANDFATHERED.has(rel)) {
      warnings.push(`[grandfathered] ${rel} (${lines} > ${CAP}) — should shrink`);
    } else {
      errors.push(`${rel} (${lines} > ${CAP}) — split into modules ≤${CAP} lines`);
    }
  }
}

if (process.argv.includes("--list-grandfather")) {
  // Print JSON array of every file currently >CAP that's not exempt.
  // Pipe to grandfather file to lock current state as the floor.
  console.log(JSON.stringify(offendersForList.sort(), null, 2));
  process.exit(0);
}

if (errors.length === 0 && warnings.length === 0) {
  console.log(`✓ audit-file-size: ${scanned} file(s) scanned, all ≤${CAP} lines`);
  process.exit(0);
}

if (warnings.length > 0) {
  console.log(`⚠ ${warnings.length} grandfathered file(s) > ${CAP} lines (backlog):`);
  for (const w of warnings) console.log(`  · ${w}`);
}
if (errors.length > 0) {
  console.error(`\n✖ ${errors.length} new violation(s):`);
  for (const e of errors) console.error(`  · ${e}`);
  console.error(
    `\n  To split: extract reusable components/utils to neighbour files, then re-run.`,
  );
}
process.exit(errors.length > 0 ? 1 : 0);

// ───────────────────────────────────────────────────────────────────

function findSourceFiles(dir, out = []) {
  let names;
  try { names = readdirSync(dir); } catch { return out; }
  for (const name of names) {
    if (
      name === "node_modules" ||
      name === ".next" ||
      name === "_generated" ||
      name.startsWith(".")
    ) continue;
    const full = path.join(dir, name);
    let s;
    try { s = statSync(full); } catch { continue; }
    if (s.isDirectory()) findSourceFiles(full, out);
    else if (/\.(ts|tsx|mjs)$/.test(name) && !name.endsWith(".test.ts") && !name.endsWith(".test.mjs")) {
      out.push(full);
    }
  }
  return out;
}
