#!/usr/bin/env node
// gen-slice-agent-md.mjs — writes `agent.md` inside every slice dir
// using the catalog metadata from packages/cli/lib/manifest.json. The
// resulting file ships with the slice when consumers run
// `npx rr add <slug>`, so the AI install prompt is available offline +
// in-tree alongside the code.
//
// Run: node scripts/features/gen-slice-agent-md.mjs [--check]
//
// --check mode: exits non-zero if any agent.md is out of date. Used by
// the slices:check pre-push gate.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, "../..");
const MANIFEST_PATH = path.join(REPO, "packages", "cli", "lib", "manifest.json");
const SITE_URL = "https://resource.rahmanef.com";

const checkMode = process.argv.includes("--check");

if (!existsSync(MANIFEST_PATH)) {
  console.error(`✖ manifest not found: ${MANIFEST_PATH}`);
  console.error(`  Run: node packages/cli/scripts/gen-manifest.mjs`);
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
const slices = manifest.slices ?? [];

let written = 0;
let drift = 0;

for (const s of slices) {
  if (!s.slug || !s.agentRecipe) continue;
  const sliceDir = resolveSliceDir(s);
  if (!sliceDir) continue;
  const target = path.join(sliceDir, "agent.md");
  const body = buildAgentMd(s);
  if (checkMode) {
    const onDisk = existsSync(target) ? readFileSync(target, "utf8") : "";
    if (onDisk !== body) {
      console.error(`✖ ${path.relative(REPO, target)} is out of date`);
      drift++;
    }
    continue;
  }
  writeFileSync(target, body);
  written++;
}

if (checkMode) {
  if (drift > 0) {
    console.error(`\nRun: node scripts/features/gen-slice-agent-md.mjs`);
    process.exit(1);
  }
  console.log(`✓ ${slices.length} slice agent.md file(s) up to date`);
} else {
  console.log(`✓ wrote ${written} slice agent.md file(s)`);
}

// ───────────────────────────────────────────────────────────────────

function resolveSliceDir(slice) {
  const candidates = [
    path.join(REPO, "frontend", "slices", slice.slug),
    path.join(REPO, "template-base", "frontend", "slices", slice.slug),
  ];
  for (const c of candidates) {
    if (existsSync(path.join(c, "slice.json"))) return c;
  }
  return null;
}

function stripVer(spec) {
  const at = spec.lastIndexOf("@");
  return at > 0 ? spec.slice(0, at) : spec;
}

function buildAgentMd(s) {
  const lines = [];
  lines.push(`<!-- AUTO-GENERATED by scripts/features/gen-slice-agent-md.mjs -->`);
  lines.push(`<!-- DO NOT EDIT — re-run \`node scripts/features/gen-slice-agent-md.mjs\` -->`);
  lines.push("");
  lines.push(`# Install \`${s.slug}\` — ${s.title}`);
  lines.push("");
  if (s.description) {
    lines.push(`> ${s.description.split(".")[0]}.`);
    lines.push("");
  }
  lines.push(`📚 Knowledge base : ${SITE_URL}/llms.txt`);
  lines.push(`📦 Slice detail   : ${SITE_URL}/slices/${s.slug}`);
  lines.push(`🧠 JSON catalog   : ${SITE_URL}/api/knowledge?slice=${s.slug}`);
  lines.push(`🤖 Prompt page    : ${SITE_URL}/agents/${s.slug}`);
  lines.push("");

  lines.push("## 1. Install");
  lines.push("");
  lines.push("```bash");
  lines.push(s.install ?? `npx rahman-resources add ${s.slug}`);
  lines.push(`# alias: npx rr add ${s.slug}`);
  lines.push("```");
  lines.push("");

  const npm = s.npmPackages ?? [];
  const dependencies = s.dependencies ?? [];
  const tags = s.tags ?? [];
  if (npm.length || dependencies.length || tags.length) {
    lines.push("## 2. What it ships");
    lines.push("");
    if (npm.length) lines.push(`- npm: \`${npm.map(stripVer).join("\`, \`")}\``);
    if (dependencies.length) lines.push(`- deps: \`${dependencies.map(stripVer).join("\`, \`")}\``);
    if (tags.length) lines.push(`- tags: ${tags.map((t) => `\`${t}\``).join(", ")}`);
    lines.push("");
  }

  if (s.agentRecipe) {
    lines.push("## 3. Wire it up");
    lines.push("");
    lines.push(s.agentRecipe);
    lines.push("");
  }

  lines.push("## Rules of engagement");
  lines.push("");
  lines.push("- shadcn-only UI primitives. No raw `<button>` / `<dialog>` / native date or file inputs.");
  lines.push("- 200-line hard cap per source file (extract neighbours when over).");
  lines.push("- All Convex queries hit an index (`.withIndex(...)`); never bare `.collect()`.");
  lines.push("- Public mutations/queries declare `args:` validators + authz.");
  lines.push(`- Full ruleset: ${SITE_URL}/best-practice`);
  lines.push("");

  return lines.join("\n");
}
